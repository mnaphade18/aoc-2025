use std::collections::HashMap;

#[derive(Debug, PartialEq, Clone)]
enum GridVal {
    Beam,
    Split,
    SplitHit,
    Start,
    Empty,
}
type Grid = Vec<Vec<GridVal>>;

fn get_pos(g: &Grid, pos: (usize, usize)) -> Option<&GridVal> {
    g.get(pos.0).and_then(|p| p.get(pos.1))
}

pub fn solve() {
    let ip = INPUT;
    //let ip = TEST;

    let grid: Grid= ip.lines().map(|l| l.chars().map(|c| match c {
        '.' => GridVal::Empty,
        'S' => GridVal::Start,
        '^' => GridVal::Split,
        '|' => GridVal::Beam,
        _ => unreachable!("Got other char"),
    }).collect()).collect();

    println!("Grdi: {:?}", grid);
    /*
    get_count(pos) -> Possbile values from that point to reach end.
        - if . returns lower value -> call get_count for 1pos below
        - if ^ calls get_count from left and right value and returns its total
    */

    let start = ip.lines().next().unwrap().find('S').unwrap();
    let mut cache = HashMap::new();

    let t = get_count((0, start), &grid, &mut cache);

    println!("Got TOtoal: {t}");
}

fn get_count(pos: (usize, usize), grid: &Grid, mut cache: &mut HashMap<(usize,usize), usize>) -> usize {
    let curr_element = grid.get(pos.0).unwrap().get(pos.1).unwrap();

    return match curr_element {
        GridVal::Start | GridVal::Empty => if let Some(_) = get_pos(grid, (pos.0+1, pos.1)) {
            get_count((pos.0+1, pos.1), grid, cache)
        } else {
            if pos.0 == grid.len()-1 {
                1
            } else {
                unreachable!("Got pos: {}, {}", pos.0, pos.1);
            }
        }
        GridVal::Split => {
            if let Some(v) = cache.get(&pos) {
                println!("cache hit for {pos:?}");
                return *v;
            }
            let left = get_count((pos.0, pos.1-1), grid, cache);
            let right = get_count((pos.0, pos.1+1), grid, cache);
            println!("FOr pos: ({pos:?}) got valued: left: {left}, right: {right}");

            cache.insert(pos, left+right);

            return left + right;
        }
        a => unreachable!("Invalid grid item: {:?}", a),
    };
}
pub fn solve1() {
    let ip = INPUT;
    //let ip = TEST;

    let mut grid: Vec<Vec<GridVal>> = ip.lines().map(|l| l.chars().map(|c| match c {
        '.' => GridVal::Empty,
        'S' => GridVal::Beam,
        '^' => GridVal::Split,
        '|' => GridVal::Beam,
        _ => unreachable!("Got other char"),
    }).collect()).collect();

    println!("Grdi: {:?}", grid);

    let mut count = 0;
    let j_len = grid.first().unwrap().len();
    for i in 0..grid.len() {
        if i == 0 {
            continue;
        }
        for j in 0..j_len {
            let top_el = (*grid.get(i-1).unwrap().get(j).unwrap()).clone();
            let elem = grid.get_mut(i).unwrap().get_mut(j).unwrap();
            let mut hit = false;

            if *elem == GridVal::Empty && top_el == GridVal::Beam {
                *elem = GridVal::Beam;
            }
            if *elem == GridVal::Split && top_el == GridVal::Beam {
                *elem = GridVal::SplitHit;
                count += 1;
                hit = true;
                println!("Hit at: ({}, {})", i, j);
            }

            if hit {
                if let Some(prev_elem) = grid.get_mut(i).unwrap().get_mut(j-1) {
                    if *prev_elem != GridVal::Split || *prev_elem != GridVal::SplitHit {
                        *prev_elem = GridVal::Beam;
                    }
                }
                if let Some(next_elem) = grid.get_mut(i).unwrap().get_mut(j+1) {
                    if *next_elem != GridVal::Split || *next_elem != GridVal::SplitHit {
                        *next_elem = GridVal::Beam;
                    }

                }
            }
        }
    }

    println!("Hit times: {}", count);
}

