fn form_floor(ip: &str) -> Vec<Vec<Option<bool>>> {
    let mut floor = Vec::new();

    for line in ip.lines() {
        let l = line.chars().into_iter().map(|c| (c == '@').then(|| true)).collect();

        floor.push(l);
    }

    return floor;
}

pub fn solve() {
    let ip = INPUT;
    let mut floor = form_floor(ip);

    let mut tot = 0;
    while let Some(removable) = get_removable_tiles(&floor) {
        println!("Removables: {:?},\n{}", removable, removable.len());
        tot += removable.len();
        for pos in removable {
            if let Some(p) = floor.get_mut(pos.0).and_then(|r| r.get_mut(pos.1)) {
                *p = None;
            }
        }
    }

    println!("Final total: {tot}");
}
fn get_removable_tiles(floor: &Vec<Vec<Option<bool>>>) -> Option<Vec<(usize, usize)>> {
    let mut removable = Vec::new();
    for (i, row) in floor.iter().enumerate() {
        for (j, element) in row.iter().enumerate() {
            if element.is_none() {
                continue;
            }

            let mut covers = 0;
            for rot_i in i.saturating_sub(1)..i+2 {
                for rot_j in j.saturating_sub(1)..j+2 {
                    if rot_i == i && rot_j == j {
                        continue;
                    }
                    if let Some(Some(_)) = floor.get(rot_i).and_then(|r| r.get(rot_j)) {
                        println!("roll present at ({},{}) for pos: ({},{})", rot_i, rot_j, i, j);
                        covers+=1;
                    }
                }
            }

            println!("Total covers for pos: ({},{}) are: {}",i,j, covers);
            if covers < 4 {
                println!("adding removable: {},{}", i,j);
                removable.push((i,j));
            }
        }
    }

    if removable.len() > 0 {
        return Some(removable);
    } else {
        return None;
    }
}

